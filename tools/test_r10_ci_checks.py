# R10 lock syntax regression: pip-compile retains bracketed extras unless
# --strip-extras is requested. Preserve each requested feature dependency.
def _synthetic_lock(extra_overrides=None, missing_hash_for=None, version_overrides=None):
    extra_overrides = extra_overrides or {}
    version_overrides = version_overrides or {}
    specs = [
        ("cryptography", "50.0.2"),
        ("uvicorn[standard]", "0.38.0"),
        ("psycopg[binary]", "3.3.0"),
        ("pwdlib[argon2]", "0.3.0"),
        ("pytest", "9.0.2"),
        ("pip-audit", "2.10.1"),
        ("httpx", "0.28.1"),
    ]
    entries = []
    for name, version in specs:
        actual = extra_overrides.get(name, name)
        actual_version = version_overrides.get(name, version)
        hash_line = "" if name == missing_hash_for else " \\" + "\n    --hash=sha256:" + "a" * 64
        entries.append(f"{actual}=={actual_version}{hash_line}\n    # via -r requirements.txt\n")
    return "# generated by pip-compile\n" + "".join(entries)


def _configure_lock_files(tmp_path, monkeypatch, content):
    requirements = tmp_path / "requirements.txt"
    requirements.write_text(
        "cryptography==50.0.2\n"
        "uvicorn[standard]>=0.30,<1.0\n"
        "psycopg[binary]>=3.2,<4.0\n"
        "pwdlib[argon2]>=0.2,<1.0\n",
        encoding="utf-8",
    )
    lock = tmp_path / "requirements-ci.lock"
    lock.write_text(content, encoding="utf-8")
    monkeypatch.setattr(ci, "ROOT", tmp_path)
    monkeypatch.setattr(ci, "LOCK", lock)


def test_lock_accepts_hashed_pins_with_required_extras(tmp_path, monkeypatch, capsys):
    _configure_lock_files(tmp_path, monkeypatch, _synthetic_lock())
    ci.verify_lock()
    assert "R10_LOCK_PASS: 7 pinned distributions" in capsys.readouterr().out


@pytest.mark.parametrize("package, stripped", [
    ("uvicorn[standard]", "uvicorn"),
    ("psycopg[binary]", "psycopg"),
    ("pwdlib[argon2]", "pwdlib"),
])
def test_lock_rejects_missing_required_extra(tmp_path, monkeypatch, package, stripped):
    _configure_lock_files(tmp_path, monkeypatch, _synthetic_lock(extra_overrides={package: stripped}))
    with pytest.raises(ci.R10CheckError, match="R10_LOCK_ROOT_REQUIREMENT_DRIFT"):
        ci.verify_lock()


def test_lock_rejects_out_of_range_version(tmp_path, monkeypatch):
    _configure_lock_files(tmp_path, monkeypatch, _synthetic_lock(version_overrides={"uvicorn[standard]": "1.1.0"}))
    with pytest.raises(ci.R10CheckError, match="R10_LOCK_ROOT_REQUIREMENT_DRIFT: uvicorn"):
        ci.verify_lock()


def test_lock_rejects_missing_package_hash(tmp_path, monkeypatch):
    _configure_lock_files(tmp_path, monkeypatch, _synthetic_lock(missing_hash_for="uvicorn[standard]"))
    with pytest.raises(ci.R10CheckError, match="R10_LOCK_PACKAGE_MISSING_HASH: uvicorn"):
        ci.verify_lock()
