// STEP 3D-D4A — TENANT/APPLICATION BROWSER ORIGIN ISOLATION
// =========================================================

function normalizeRuntimeScopeId(
  value: string
): string {
  return String(value || "")
    .trim()
    .toLowerCase()
    .replace(
      /[^a-z0-9]/g,
      ""
    );
}


function buildRuntimeScopeHostname(
  tenantId: string,
  applicationId: string
): string {

  const tenant =
    normalizeRuntimeScopeId(
      tenantId
    );

  const application =
    normalizeRuntimeScopeId(
      applicationId
    );


  if (
    tenant.length < 8 ||
    application.length < 8
  ) {
    throw new Error(
      "Invalid tenant/application runtime scope."
    );
  }


  /*
   * Keep DNS label safely below the
   * 63-character label limit.
   *
   * Tenant:
   * first 8 compact UUID characters.
   *
   * Application:
   * full compact UUID.
   *
   * Example:
   *
   * t-b6e8ccbc-a-d350243378ad4222bfaef961c8ee364f
   */
  const scopeLabel =
    `t-${tenant.slice(0, 8)}` +
    `-a-${application.slice(0, 32)}`;


  const suffix =
    (
      process.env
        .NEXT_PUBLIC_RUNTIME_HOST_SUFFIX ??
      "runtime.localhost"
    )
      .trim()
      .toLowerCase()
      .replace(
        /^\.+|\.+$/g,
        ""
      );


  if (!suffix) {
    throw new Error(
      "AUGMIS runtime host suffix is not configured."
    );
  }


  return (
    `${scopeLabel}.${suffix}`
  );
}


// =========================================================
// Public isolated runtime URL helper
// =========================================================

export function toIsolatedRuntimeGatewayUrl(
  backendRuntimeUrl: string,
  tenantId: string,
  applicationId: string
): string {

  /*
   * First use the existing gateway conversion.
   *
   * This preserves all current:
   *
   * - runtime ID parsing
   * - ticket handling
   * - gateway path handling
   * - security validation
   */
  const normalGatewayUrl =
    toRuntimeGatewayUrl(
      backendRuntimeUrl
    );


  const url =
    new URL(
      normalGatewayUrl
    );


  url.hostname =
    buildRuntimeScopeHostname(
      tenantId,
      applicationId
    );


  /*
   * Existing protocol, port, pathname,
   * query string and launch ticket remain
   * unchanged.
   */
  return url.toString();
}


export function rewriteBackendLocation(
  location: string,
  runtimeId: string,
  frontendOrigin: string
): string {
  const safeRuntimeId =
    validateRuntimeId(runtimeId);

  const backendBase =
    getRuntimeApiBaseUrl();

  const backendLocation =
    new URL(
      location,
      `${backendBase}/`
    );

  const expectedPrefix =
    `/api/v1/static-runtime/` +
    `${safeRuntimeId}/`;

  /*
   * Never allow FastAPI to redirect this
   * runtime gateway to another runtime,
   * API route or external origin.
   */
  if (
    !backendLocation.pathname.startsWith(
      expectedPrefix
    )
  ) {
    throw new Error(
      "Cross-runtime redirect blocked."
    );
  }

  const relative =
    backendLocation.pathname.slice(
      expectedPrefix.length
    );

  const target =
    new URL(
      `/runtime/${encodeURIComponent(
        safeRuntimeId
      )}/`,
      frontendOrigin
    );

  if (relative) {
    const segments =
      validateAssetPath(
        relative
          .split("/")
          .filter(Boolean)
          .map((part) =>
            decodeURIComponent(part)
          )
      );

    target.pathname += segments
      .map((segment) =>
        encodeURIComponent(segment)
      )
      .join("/");
  }

  target.search =
    backendLocation.search;

  return (
    target.pathname +
    target.search
  );
}


export function rewriteRuntimeCookie(
  setCookie: string,
  runtimeId: string
): string {
  const safeRuntimeId =
    validateRuntimeId(runtimeId);

  const expectedCookieName =
    getRuntimeCookieName(
      safeRuntimeId
    );

  const firstPart =
    setCookie
      .split(";", 1)[0]
      ?.trim();

  const equalsIndex =
    firstPart?.indexOf("=") ?? -1;

  if (equalsIndex <= 0) {
    throw new Error(
      "Invalid runtime cookie."
    );
  }

  const cookieName =
    firstPart!.slice(
      0,
      equalsIndex
    );

  /*
   * Critical 3D-D2 boundary:
   *
   * Runtime A may only establish
   * Runtime A's cookie.
   */
  if (
    cookieName !==
    expectedCookieName
  ) {
    throw new Error(
      "Unexpected runtime cookie."
    );
  }

  const attributes =
    setCookie
      .split(";")
      .map((part) =>
        part.trim()
      )
      .filter(Boolean);

  const rewritten =
    attributes.filter(
      (attribute, index) => {
        if (index === 0) {
          return true;
        }

        const lower =
          attribute.toLowerCase();

        return !(
          lower.startsWith("path=") ||
          lower.startsWith("domain=")
        );
      }
    );

  /*
   * Browser-side cookie is scoped to
   * this runtime only.
   */
  rewritten.push(
    `Path=/runtime/${encodeURIComponent(
      safeRuntimeId
    )}/`
  );

  return rewritten.join("; ");
}


export function removeSecureCookieFlag(
  setCookie: string
): string {
  return setCookie
    .split(";")
    .map((part) =>
      part.trim()
    )
    .filter(
      (part) =>
        part.toLowerCase() !==
        "secure"
    )
    .join("; ");
}


export function buildRuntimeCookieHeader(
  cookieName: string,
  cookieValue: string
): string {
  if (!cookieName) {
    throw new Error(
      "Runtime cookie name is required."
    );
  }

  if (!cookieValue) {
    throw new Error(
      "Runtime cookie value is required."
    );
  }

  /*
   * AUGMIS runtime tickets are generated by
   * Python secrets.token_urlsafe(), therefore
   * their values contain URL-safe characters.
   *
   * Do not decode, encode or otherwise mutate
   * the value before forwarding it to FastAPI.
   */
  return `${cookieName}=${cookieValue}`;
}