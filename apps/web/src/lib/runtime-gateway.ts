// apps/web/src/lib/runtime-gateway.ts
const DEFAULT_RUNTIME_API_BASE_URL =
  "http://127.0.0.1:8001";


function getRuntimeApiBaseUrl(): string {
  const value =
    process.env.AUGMIS_RUNTIME_API_BASE_URL ??
    process.env.NEXT_PUBLIC_API_BASE_URL ??
    DEFAULT_RUNTIME_API_BASE_URL;

  return value.replace(/\/+$/, "");
}


/*
 * Must remain identical to:
 *
 * _static_runtime_cookie_name()
 *
 * in FastAPI.
 */
export function getRuntimeCookieName(
  runtimeId: string
): string {
  const safe = Array.from(runtimeId)
    .filter((character) =>
      /[A-Za-z0-9_-]/.test(character)
    )
    .join("");

  return (
    "augmis_static_" +
    safe.slice(0, 24)
  );
}


export function validateRuntimeId(
  runtimeId: string
): string {
  const value = runtimeId.trim();

  if (!value) {
    throw new Error(
      "Runtime ID is required."
    );
  }

  /*
   * Runtime IDs generated by AUGMIS are
   * URL-safe opaque identifiers.
   *
   * Do not allow path syntax to become
   * part of a runtime identifier.
   */
  if (
    value.includes("/") ||
    value.includes("\\") ||
    value.includes("..")
  ) {
    throw new Error(
      "Invalid runtime ID."
    );
  }

  if (
    !/^[A-Za-z0-9_-]+$/.test(value)
  ) {
    throw new Error(
      "Invalid runtime ID."
    );
  }

  return value;
}


function validateAssetSegment(
  segment: string
): string {
  let decoded: string;

  try {
    decoded =
      decodeURIComponent(segment);
  } catch {
    throw new Error(
      "Invalid runtime asset path."
    );
  }

  if (
    !decoded ||
    decoded === "." ||
    decoded === ".."
  ) {
    throw new Error(
      "Invalid runtime asset path."
    );
  }

  if (
    decoded.includes("/") ||
    decoded.includes("\\") ||
    decoded.includes("\0")
  ) {
    throw new Error(
      "Invalid runtime asset path."
    );
  }

  /*
   * Defence against Windows-style
   * drive-qualified paths.
   */
  if (
    /^[A-Za-z]:/.test(decoded)
  ) {
    throw new Error(
      "Invalid runtime asset path."
    );
  }

  return decoded;
}


export function validateAssetPath(
  assetPath: string[]
): string[] {
  return assetPath.map(
    validateAssetSegment
  );
}


export function buildBackendRuntimeUrl(
  runtimeId: string,
  assetPath: string[],
  search = ""
): URL {
  const safeRuntimeId =
    validateRuntimeId(runtimeId);

  const safeAssetPath =
    validateAssetPath(assetPath);

  const baseUrl =
    getRuntimeApiBaseUrl();

  let path =
    `${baseUrl}/api/v1/static-runtime/` +
    `${encodeURIComponent(safeRuntimeId)}/`;

  if (safeAssetPath.length > 0) {
    path += safeAssetPath
      .map((segment) =>
        encodeURIComponent(segment)
      )
      .join("/");
  }

  const url = new URL(path);

  if (search) {
    const source =
      new URLSearchParams(
        search.startsWith("?")
          ? search.slice(1)
          : search
      );

    /*
     * Only the launch ticket is meaningful
     * to the static runtime gateway.
     *
     * Do not blindly forward arbitrary
     * platform query parameters.
     */
    const ticket =
      source.get("ticket");

    if (ticket) {
      url.searchParams.set(
        "ticket",
        ticket
      );
    }
  }

  return url;
}


export function toRuntimeGatewayUrl(
  backendRuntimeUrl: string
): string {

  const backendUrl =
    new URL(
      backendRuntimeUrl
    );


  const marker =
    "/api/v1/static-runtime/";


  const markerIndex =
    backendUrl.pathname.indexOf(
      marker
    );


  if (markerIndex === -1) {
    throw new Error(
      "Invalid AUGMIS static runtime URL."
    );
  }


  const remainder =
    backendUrl.pathname.slice(
      markerIndex +
      marker.length
    );


  const parts =
    remainder
      .split("/")
      .filter(Boolean);


  if (parts.length < 1) {
    throw new Error(
      "Runtime ID is missing."
    );
  }


  const runtimeId =
    decodeURIComponent(
      parts[0]
    );


  validateRuntimeId(
    runtimeId
  );


  const runtimeOrigin =
    (
      process.env
        .NEXT_PUBLIC_RUNTIME_GATEWAY_ORIGIN
      ??
      "http://127.0.0.1:3000"
    ).replace(
      /\/+$/,
      ""
    );


  const gatewayUrl =
    new URL(
      `/runtime/${encodeURIComponent(
        runtimeId
      )}/`,
      runtimeOrigin
    );


  /*
   * Preserve the one-time FastAPI launch ticket.
   */
  gatewayUrl.search =
    backendUrl.search;


  return gatewayUrl.toString();
}


